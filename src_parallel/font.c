const uint8_t *get_font_char(char character, font_type_t type){
  unsigned char character_code = (unsigned char)character;

  switch(type){
    case FONT_5X5:
      if(character_code >= 32 && character_code <= 126){
        return fonts[type].font_chars[character_code - 32];
      }

      return fonts[type].font_unknown;
      break;

    case FONT_6X8:
      if(character_code >= 32 && character_code <= 126){
        return fonts[type].font_chars[character_code - 32];
      }

      return fonts[type].font_unknown;
      break;
  }

  return NULL;
}