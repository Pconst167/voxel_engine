const uint8_t *get_font_5x7_char(char character){
  static const uint8_t space[7]        = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
  static const uint8_t exclamation[7]  = {0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04};
  static const uint8_t double_quote[7] = {0x0A, 0x0A, 0x0A, 0x00, 0x00, 0x00, 0x00};
  static const uint8_t hash[7]         = {0x0A, 0x0A, 0x1F, 0x0A, 0x1F, 0x0A, 0x0A};
  static const uint8_t dollar[7]       = {0x04, 0x0F, 0x14, 0x0E, 0x05, 0x1E, 0x04};
  static const uint8_t percent[7]      = {0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03};
  static const uint8_t ampersand[7]    = {0x0C, 0x12, 0x14, 0x08, 0x15, 0x12, 0x0D};
  static const uint8_t apostrophe[7]   = {0x04, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00};
  static const uint8_t left_paren[7]   = {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02};
  static const uint8_t right_paren[7]  = {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08};
  static const uint8_t asterisk[7]     = {0x00, 0x04, 0x15, 0x0E, 0x15, 0x04, 0x00};
  static const uint8_t plus[7]         = {0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00};
  static const uint8_t comma[7]        = {0x00, 0x00, 0x00, 0x00, 0x04, 0x04, 0x08};
  static const uint8_t minus[7]        = {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00};
  static const uint8_t dot[7]          = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
  static const uint8_t slash[7]        = {0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10};

  static const uint8_t colon[7]        = {0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00};
  static const uint8_t semicolon[7]    = {0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x08};
  static const uint8_t less_than[7]    = {0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02};
  static const uint8_t equals[7]       = {0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00};
  static const uint8_t greater_than[7] = {0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08};
  static const uint8_t question[7]     = {0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04};
  static const uint8_t at_sign[7]      = {0x0E, 0x11, 0x17, 0x15, 0x17, 0x10, 0x0E};

  static const uint8_t left_square[7]  = {0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E};
  static const uint8_t backslash[7]    = {0x10, 0x10, 0x08, 0x04, 0x02, 0x01, 0x01};
  static const uint8_t right_square[7] = {0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E};
  static const uint8_t caret[7]        = {0x04, 0x0A, 0x11, 0x00, 0x00, 0x00, 0x00};
  static const uint8_t underscore[7]   = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1F};
  static const uint8_t backtick[7]     = {0x08, 0x04, 0x02, 0x00, 0x00, 0x00, 0x00};

  static const uint8_t left_brace[7]   = {0x02, 0x04, 0x04, 0x08, 0x04, 0x04, 0x02};
  static const uint8_t pipe[7]         = {0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04};
  static const uint8_t right_brace[7]  = {0x08, 0x04, 0x04, 0x02, 0x04, 0x04, 0x08};
  static const uint8_t tilde[7]        = {0x00, 0x00, 0x08, 0x15, 0x02, 0x00, 0x00};

  if(character >= '0' && character <= '9')
    return font_5x7_digits[character - '0'];

  if(character >= 'A' && character <= 'Z')
    return font_5x7_letters[character - 'A'];

  if(character >= 'a' && character <= 'z')
    return font_5x7_letters[character - 'a'];

  switch(character){
    case ' ':  return space;
    case '!':  return exclamation;
    case '"':  return double_quote;
    case '#':  return hash;
    case '$':  return dollar;
    case '%':  return percent;
    case '&':  return ampersand;
    case '\'': return apostrophe;
    case '(':  return left_paren;
    case ')':  return right_paren;
    case '*':  return asterisk;
    case '+':  return plus;
    case ',':  return comma;
    case '-':  return minus;
    case '.':  return dot;
    case '/':  return slash;
    case ':':  return colon;
    case ';':  return semicolon;
    case '<':  return less_than;
    case '=':  return equals;
    case '>':  return greater_than;
    case '?':  return question;
    case '@':  return at_sign;
    case '[':  return left_square;
    case '\\': return backslash;
    case ']':  return right_square;
    case '^':  return caret;
    case '_':  return underscore;
    case '`':  return backtick;
    case '{':  return left_brace;
    case '|':  return pipe;
    case '}':  return right_brace;
    case '~':  return tilde;
  }

  return space;
}